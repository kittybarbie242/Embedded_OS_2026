#include "tft_gui.h"
#include <stdio.h>
#include <fcntl.h>
#include <unistd.h>

static int fd_tft = -1;
static uint16_t frame_buffer[128 * 160];

// Bộ Font mini 3x5
static const uint8_t font3x5[][3] = {
    {0x00,0x00,0x00}, {0x00,0x5F,0x00}, {0x03,0x00,0x03}, {0x14,0x3E,0x14}, // Space, !, ", #
    {0x24,0x2A,0x12}, {0x23,0x13,0x08}, {0x1A,0x25,0x22}, {0x00,0x03,0x00}, // $, %, &, '
    {0x1C,0x22,0x41}, {0x41,0x22,0x1C}, {0x0A,0x04,0x0A}, {0x04,0x0E,0x04}, // (, ), *, +
    {0x40,0x20,0x00}, {0x04,0x04,0x04}, {0x00,0x20,0x00}, {0x02,0x04,0x08}, // ,, -, ., /
    {0x3E,0x22,0x3E}, {0x00,0x3E,0x00}, {0x3A,0x2A,0x2E}, {0x2A,0x2A,0x3E}, // 0, 1, 2, 3
    {0x0E,0x08,0x3E}, {0x2E,0x2A,0x3A}, {0x3E,0x2A,0x3A}, {0x02,0x02,0x3E}, // 4, 5, 6, 7
    {0x3E,0x2A,0x3E}, {0x2E,0x2A,0x3E}, {0x00,0x14,0x00}, {0x00,0x24,0x00}, // 8, 9, :, ;
    {0x08,0x14,0x22}, {0x14,0x14,0x14}, {0x22,0x14,0x08}, {0x02,0x29,0x06}, // <, =, >, ?
    {0x3E,0x21,0x2D}, {0x3E,0x09,0x3E}, {0x3E,0x2A,0x14}, {0x1C,0x22,0x22}, // @, A, B, C
    {0x3E,0x22,0x1C}, {0x3E,0x2A,0x2A}, {0x3E,0x0A,0x0A}, {0x1C,0x22,0x3A}, // D, E, F, G
    {0x3E,0x08,0x3E}, {0x00,0x3E,0x00}, {0x10,0x20,0x1F}, {0x3E,0x08,0x36}, // H, I, J, K
    {0x3E,0x20,0x20}, {0x3E,0x04,0x3E}, {0x3E,0x06,0x3E}, {0x1C,0x22,0x1C}, // L, M, N, O
    {0x3E,0x0A,0x0C}, {0x1C,0x2A,0x3C}, {0x3E,0x1A,0x2E}, {0x2E,0x2A,0x3A}, // P, Q, R, S
    {0x02,0x3E,0x02}, {0x3E,0x20,0x3E}, {0x1E,0x20,0x1E}, {0x3E,0x10,0x3E}, // T, U, V, W
    {0x36,0x08,0x36}, {0x0E,0x30,0x0E}, {0x32,0x2A,0x26},                     // X, Y, Z
    {0x3E,0x10,0x0E}, {0x24,0x2A,0x34}, {0x00,0x00,0x00}, {0x00,0x00,0x00},
    {0x3E,0x08,0x14}, {0x3E,0x08,0x38}, {0x28,0x38,0x28}
};

int tft_init(const char* dev_path) {
    fd_tft = open(dev_path, O_WRONLY);
    if (fd_tft < 0) return -1;
    return 0;
}

void tft_close(void) {
    if (fd_tft >= 0) close(fd_tft);
}

void tft_fill_screen(uint16_t color) {
    for (int i = 0; i < 128 * 160; i++) {
        frame_buffer[i] = (color >> 8) | (color << 8); // Đảo byte Endianness
    }
}

static void tft_draw_pixel(int x, int y, uint16_t color) {
    if (x < 0 || x >= 128 || y < 0 || y >= 160) return;
    frame_buffer[y * 128 + x] = (color >> 8) | (color << 8);
}

static void tft_draw_char(int x, int y, char c, uint16_t color, uint16_t bg, uint8_t scale) {
    uint8_t index;
    
    // Ép hết thành chữ HOA, không cần custom font
    if (c >= 'a' && c <= 'z') index = (c - 32) - 32; 
    else if (c >= 32 && c <= 90) index = c - 32; 
    else index = 0; // Ký tự lạ thì biến thành khoảng trắng
    
    for (int i = 0; i < 3; i++) {
        uint8_t line = font3x5[index][i];
        for (int j = 0; j < 8; j++) { 
            if (line & (1 << j)) {
                for (int sx = 0; sx < scale; sx++)
                    for (int sy = 0; sy < scale; sy++)
                        tft_draw_pixel(x + i*scale + sx, y + j*scale + sy, color);
            } else if (bg != color) {
                for (int sx = 0; sx < scale; sx++)
                    for (int sy = 0; sy < scale; sy++)
                        tft_draw_pixel(x + i*scale + sx, y + j*scale + sy, bg);
            }
        }
    }
}

void tft_draw_string(int x, int y, const char *str, uint16_t color, uint16_t bg, uint8_t scale) {
    while (*str) {
        tft_draw_char(x, y, *str, color, bg, scale);
        x += (3 * scale) + (1 * scale); 
        str++;
    }
}

void tft_update(void) {
    if (fd_tft >= 0) {
        write(fd_tft, frame_buffer, sizeof(frame_buffer));
    }
}
